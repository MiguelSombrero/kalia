#!/usr/bin/env node
// Writes the path templates of backend/openapi.json beside the generated
// client, so a transport can log `/api/v1/cellars/{username}` where the
// generated code hands it only `/api/v1/cellars/jouni` (ADR-0013). Runs after
// orval in `npm run generate`, which cleans the directory first.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(resolve(here, "../../../backend/openapi.json"), "utf8"));
const out = resolve(here, "../src/generated/route-templates.ts");

const lines = Object.keys(spec.paths)
  .sort()
  .map((template) => `  ${JSON.stringify(template)},`);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/generate-route-templates.mjs from backend/openapi.json. Do not edit.\n\nexport const routeTemplates = [\n${lines.join("\n")}\n] as const;\n`);
