import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { tokens } from "../packages/tokens/src/tokens.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const outputPaths = {
  web: "web/app/tokens.generated.css",
  mobile: "mobile/src/lib/design/theme.generated.ts",
  keycloak: "keycloak/themes/kalia/login/resources/css/tokens.generated.css",
};
const families = ["primitives", "colors", "fonts", "typography", "weights", "spacing", "radius", "duration", "easing", "variants"];
const allowed = (token, platform) => (token.platforms ?? ["web", "mobile"]).includes(platform);
const length = /^(?:0|(?:\d+(?:\.\d+)?|\.\d+)(?:rem|px))$/;
const numeric = /^(?:\d+(?:\.\d+)?|\.\d+)$/;
const spacing = /^(?:\d+(?:\.\d+)?|\.\d+)(?:em|rem|px)$/;

export function validateTokens(source) {
  for (const family of families) {
    if (!Array.isArray(source[family])) throw new Error(`${family}: expected a token list`);
    const names = new Set();
    for (const token of source[family]) {
      if (typeof token.name !== "string" || !/^[a-z][a-z0-9-]*$/.test(token.name)) throw new Error(`${family}: invalid token name ${token.name}`);
      if (names.has(token.name)) throw new Error(`${token.name}: duplicate name in ${family}`);
      names.add(token.name);
      if (token.platforms && (!Array.isArray(token.platforms) || token.platforms.some((p) => !["web", "mobile", "keycloak"].includes(p)))) throw new Error(`${token.name}: invalid platforms`);
    }
  }
  const primitives = new Map(source.primitives.map((token) => [token.name, token]));
  const alias = (token, value, owner = token) => {
    const primitive = primitives.get(value);
    if (typeof value !== "string" || !primitive) throw new Error(`${token.name}: invalid primitive alias ${value}`);
    for (const platform of ["web", "mobile"].filter((p) => allowed(owner, p))) {
      if (!allowed(primitive, platform)) throw new Error(`${token.name}: primitive ${value} is unavailable on ${platform}`);
    }
  };
  for (const token of source.primitives) {
    if (typeof token.value !== "string" || !/^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(token.value)) throw new Error(`${token.name}: expected a hex color`);
  }
  for (const token of source.colors) for (const mode of ["light", "dark"]) alias(token, token[mode]);
  for (const token of source.fonts) {
    for (const platform of ["web", "mobile", "keycloak"].filter((p) => allowed(token, p))) {
      if (typeof token.values?.[platform] !== "string" || !token.values[platform].trim()) throw new Error(`${token.name}: missing ${platform} font`);
    }
  }
  for (const token of source.typography) {
    if (!length.test(token.size) || !(length.test(token.lineHeight) || numeric.test(token.lineHeight)) || (token.letterSpacing !== undefined && !spacing.test(token.letterSpacing))) throw new Error(`${token.name}: invalid typography value`);
  }
  for (const family of ["spacing", "radius"]) for (const token of source[family]) if (!length.test(token.value)) throw new Error(`${token.name}: invalid ${family} value`);
  for (const token of source.duration) if (!/^\d+(?:\.\d+)?ms$/.test(token.value)) throw new Error(`${token.name}: invalid duration`);
  for (const token of source.weights) if (!/^[1-9]00$/.test(token.value)) throw new Error(`${token.name}: invalid weight`);
  for (const token of source.easing) if (!/^(?:linear|ease|ease-in|ease-out|ease-in-out|cubic-bezier\([^)]+\))$/.test(token.value)) throw new Error(`${token.name}: invalid easing`);
  for (const group of source.variants) {
    if (!Array.isArray(group.values)) throw new Error(`${group.name}: invalid variants`);
    const names = new Set();
    for (const variant of group.values) {
      if (names.has(variant.name)) throw new Error(`${variant.name}: duplicate variant`);
      names.add(variant.name);
      for (const mode of ["light", "dark"]) {
        alias(variant, variant[mode]?.background, group);
        alias(variant, variant[mode]?.foreground, group);
      }
    }
  }
}

function points(value, size = 1) {
  if (value.endsWith("rem")) return Number.parseFloat(value) * 16;
  if (value.endsWith("em")) return Number((Number.parseFloat(value) * size).toFixed(6));
  return Number.parseFloat(value);
}

export function generate(source) {
  validateTokens(source);
  const primitive = Object.fromEntries(source.primitives.map((token) => [token.name, token.value]));
  const selected = (family, platform) => source[family].filter((token) => allowed(token, platform));
  const web = ["/* Generated by scripts/generate-tokens.mjs; do not edit. */", ":root {"];
  for (const token of selected("primitives", "web")) web.push(`  --${token.name}: ${token.value};`);
  for (const token of selected("colors", "web")) web.push(`  --${token.name}: var(--${token.light});`);
  for (const family of ["duration", "easing"]) for (const token of selected(family, "web")) web.push(`  --motion-${family}-${token.name}: ${token.value};`);
  web.push("}", "");
  for (const group of selected("variants", "web")) {
    for (const variant of group.values) web.push(`[data-${group.name}="${variant.name}"] { --style: var(--${variant.light.background}); --style-foreground: var(--${variant.light.foreground}); }`);
  }
  web.push("", "@theme inline {");
  for (const token of selected("colors", "web")) web.push(`  --color-${token.name}: var(--${token.name});`);
  for (const token of selected("fonts", "web")) {
    web.push(`  --font-${token.name}: ${token.values.web};`);
    if (token.webVariation) web.push(`  --font-${token.name}--font-variation-settings: ${token.webVariation};`);
  }
  for (const token of selected("typography", "web")) {
    web.push(`  --text-${token.name}: ${token.size};`, `  --text-${token.name}--line-height: ${token.lineHeight};`);
    if (token.letterSpacing) web.push(`  --text-${token.name}--letter-spacing: ${token.letterSpacing};`);
  }
  for (const token of selected("spacing", "web")) web.push(`  --spacing-${token.name}: ${token.value};`);
  for (const token of selected("weights", "web")) web.push(`  --font-weight-${token.name}: ${token.value};`);
  for (const token of selected("radius", "web")) web.push(`  --radius-${token.name}: ${token.value};`);
  web.push("}", "");

  const colors = Object.fromEntries(["light", "dark"].map((mode) => [mode, Object.fromEntries(selected("colors", "mobile").map((token) => [token.name, primitive[token[mode]]]))]));
  const typography = Object.fromEntries(selected("typography", "mobile").map((token) => {
    const size = points(token.size);
    const result = { size, lineHeight: numeric.test(token.lineHeight) ? points(token.lineHeight) * size : points(token.lineHeight) };
    if (token.letterSpacing) result.letterSpacing = points(token.letterSpacing, size);
    return [token.name, result];
  }));
  const variants = Object.fromEntries(selected("variants", "mobile").map((group) => [group.name, Object.fromEntries(group.values.map((variant) => [variant.name, Object.fromEntries(["light", "dark"].map((mode) => [mode, { background: primitive[variant[mode].background], foreground: primitive[variant[mode].foreground] }]))]))]));
  const mobileData = {
    colors,
    fonts: Object.fromEntries(selected("fonts", "mobile").map((token) => [token.name, token.values.mobile])),
    typography,
    weights: Object.fromEntries(selected("weights", "mobile").map((token) => [token.name, token.value])),
    ...Object.fromEntries(["spacing", "radius", "duration", "easing"].map((family) => [family, Object.fromEntries(selected(family, "mobile").map((token) => [token.name, family === "easing" ? token.value : points(token.value)]))])),
    variants,
  };
  const mobile = `// Generated by scripts/generate-tokens.mjs; do not edit.\nexport const theme = ${JSON.stringify(mobileData, null, 2)} as const;\n`;
  const keycloak = ["/* Generated by scripts/generate-tokens.mjs; do not edit. */", ":root {"];
  for (const token of selected("colors", "keycloak")) keycloak.push(`  --kalia-color-${token.name}: ${primitive[token.light]};`);
  for (const token of selected("fonts", "keycloak")) keycloak.push(`  --kalia-font: ${token.values.keycloak};`);
  keycloak.push("}", "");
  return { web: web.join("\n"), mobile, keycloak: keycloak.join("\n") };
}

export function checkOutputs(outputs, base = root) {
  const failures = [];
  for (const [platform, path] of Object.entries(outputPaths)) {
    let existing;
    try {
      existing = readFileSync(resolve(base, path), "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (existing !== outputs[platform]) failures.push(`${path}: generated output is missing or out of date`);
  }
  return failures;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputs = generate(tokens);
  if (process.argv.includes("--check")) {
    const failures = checkOutputs(outputs);
    for (const failure of failures) console.error(failure);
    if (failures.length) process.exitCode = 1;
  } else {
    for (const [platform, path] of Object.entries(outputPaths)) {
      writeFileSync(resolve(root, path), outputs[platform]);
      console.log(`Generated ${path}`);
    }
  }
}
